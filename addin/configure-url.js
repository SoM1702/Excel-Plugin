/*
 * Build a static deployment bundle and XML manifest for the hosted add-in.
 *
 * Usage:
 *   node configure-url.js <frontend-base-url> <backend-api-url> <provider-name> <support-url>
 *
 * Example:
 *   node configure-url.js https://team.github.io/Excel-Plugin/addin \
 *     https://excel-api.example.com "Team Name" https://team.example.com/support
 *
 * The generated addin/dist directory contains only the task-pane assets and
 * runtime API configuration. The local development files keep localhost URLs.
 */

const fs = require("fs");
const path = require("path");

const xml2js = require("xml2js");

const ADDIN_DIR = __dirname;
const SOURCE_MANIFEST = path.join(ADDIN_DIR, "manifest.xml");
const OUTPUT_DIR = path.join(ADDIN_DIR, "dist");
const OUTPUT_MARKER = ".excel-logistic-regression-generated";

function validateHttpsUrl(value, label, { allowPath = true } = {}) {
  let parsed;
  try {
    parsed = new URL(value);
  } catch {
    throw new Error(`${label} must be a valid HTTPS URL.`);
  }
  if (
    parsed.protocol !== "https:" ||
    !parsed.hostname ||
    parsed.username ||
    parsed.password ||
    parsed.search ||
    parsed.hash ||
    (!allowPath && parsed.pathname !== "/")
  ) {
    throw new Error(`${label} must be an HTTPS URL without credentials, query, or fragment.`);
  }
  return parsed.toString().replace(/\/$/, "");
}

function xmlEscape(value) {
  return String(value).replace(/[<>&"']/g, (char) => {
    const entities = { "<": "&lt;", ">": "&gt;", "&": "&amp;", '"': "&quot;", "'": "&apos;" };
    return entities[char];
  });
}

function replaceRequired(xml, pattern, replacement, label) {
  if (!pattern.test(xml)) throw new Error(`Manifest is missing its ${label} element.`);
  return xml.replace(pattern, () => replacement);
}

function assertValidXml(xmlString) {
  let parseErr = null;
  let parsedDoc = null;
  xml2js.parseString(xmlString, (err, result) => {
    parseErr = err;
    parsedDoc = result;
  });
  if (parseErr) {
    throw new Error(`Generated manifest XML is invalid: ${parseErr.message}`);
  }
  return parsedDoc;
}

function prepareOutputDirectory(outputDir, mayReplaceGenerated) {
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
    return;
  }
  const markerPath = path.join(outputDir, OUTPUT_MARKER);
  const expectedMarker = "Generated by configure-url.js; safe to replace on the next build.\n";
  if (
    !mayReplaceGenerated ||
    !fs.existsSync(markerPath) ||
    fs.readFileSync(markerPath, "utf8") !== expectedMarker
  ) {
    throw new Error(
      `Refusing to replace existing output directory without generated marker: ${outputDir}`
    );
  }
  fs.rmSync(outputDir, { recursive: true, force: true });
  fs.mkdirSync(outputDir, { recursive: true });
}

function buildDeployment({ frontendBaseUrl, backendApiUrl, providerName, supportUrl, outputDir = OUTPUT_DIR }) {
  const frontend = validateHttpsUrl(frontendBaseUrl, "Frontend base URL");
  const backend = validateHttpsUrl(backendApiUrl, "Backend API URL");
  const support = validateHttpsUrl(supportUrl, "Support URL");
  const provider = String(providerName || "").trim();
  if (!provider || /your\s+team\s+name/i.test(provider)) {
    throw new Error("Provide the real provider or team name used for this deployment.");
  }

  const sourceXml = fs.readFileSync(SOURCE_MANIFEST, "utf8");
  if (!sourceXml.includes("https://localhost:3001")) {
    throw new Error("The source manifest does not contain the expected local asset URLs.");
  }
  const frontendXml = xmlEscape(frontend);
  const providerXml = xmlEscape(provider);
  const supportXml = xmlEscape(support);

  let productionXml = sourceXml.replace(/https:\/\/localhost:3001/g, () => frontendXml);
  productionXml = replaceRequired(
    productionXml,
    /<ProviderName>[\s\S]*?<\/ProviderName>/,
    `<ProviderName>${providerXml}</ProviderName>`,
    "ProviderName"
  );
  productionXml = replaceRequired(
    productionXml,
    /<SupportUrl\s+DefaultValue="[^"]*"\s*\/>/,
    `<SupportUrl DefaultValue="${supportXml}"/>`,
    "SupportUrl"
  );

  assertValidXml(productionXml);

  const isDefaultGeneratedDirectory = path.resolve(outputDir) === path.resolve(OUTPUT_DIR);
  prepareOutputDirectory(outputDir, isDefaultGeneratedDirectory);
  fs.cpSync(path.join(ADDIN_DIR, "src"), path.join(outputDir, "src"), { recursive: true });
  fs.cpSync(path.join(ADDIN_DIR, "assets"), path.join(outputDir, "assets"), { recursive: true });
  fs.writeFileSync(
    path.join(outputDir, "src", "taskpane", "config.js"),
    `window.EXCEL_LOGISTIC_REGRESSION_CONFIG = Object.freeze({ backendUrl: ${JSON.stringify(backend)} });\n`
  );
  fs.writeFileSync(path.join(outputDir, "index.html"), "<!doctype html><title>Excel Logistic Regression Add-in</title>\n");
  fs.writeFileSync(
    path.join(outputDir, OUTPUT_MARKER),
    "Generated by configure-url.js; safe to replace on the next build.\n"
  );
  fs.writeFileSync(path.join(outputDir, "manifest.prod.xml"), productionXml);

  return { outputDir, manifestPath: path.join(outputDir, "manifest.prod.xml"), frontend, backend };
}

if (require.main === module) {
  const [, , frontendBaseUrl, backendApiUrl, providerName, supportUrl] = process.argv;
  if (!frontendBaseUrl || !backendApiUrl || !providerName || !supportUrl) {
    console.error("Usage: node configure-url.js <frontend-base-url> <backend-api-url> <provider-name> <support-url>");
    console.error("All URLs must use HTTPS. Example values are in the file header.");
    process.exitCode = 1;
  } else {
    try {
      const result = buildDeployment({ frontendBaseUrl, backendApiUrl, providerName, supportUrl });
      console.log(`Built static site: ${result.outputDir}`);
      console.log(`Generated manifest: ${result.manifestPath}`);
      console.log(`Frontend: ${result.frontend}`);
      console.log(`Backend: ${result.backend}`);
    } catch (error) {
      console.error(error.message);
      process.exitCode = 1;
    }
  }
}

module.exports = { buildDeployment, validateHttpsUrl };
